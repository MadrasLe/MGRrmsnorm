refresh_cuda_python_libs() {
  CUDA_PY_LIB_DIRS="$(python - <<'PY'
import site
import sysconfig
from pathlib import Path

roots = []

def add_root(raw):
    if not raw:
        return
    path = Path(raw)
    if path.exists() and path not in roots:
        roots.append(path)

try:
    for item in site.getsitepackages():
        add_root(item)
except Exception:
    pass
try:
    add_root(site.getusersitepackages())
except Exception:
    pass
try:
    paths = sysconfig.get_paths()
    add_root(paths.get("purelib"))
    add_root(paths.get("platlib"))
except Exception:
    pass

dirs = []

def add_dir(path):
    text = str(path)
    if path.exists() and text not in dirs:
        dirs.append(text)

for root in roots:
    for path in root.glob("nvidia/**/lib"):
        add_dir(path)
    for path in root.glob("nvidia/**/lib64"):
        add_dir(path)
    for path in root.rglob("libcudart.so*"):
        add_dir(path.parent)

print(":".join(dirs))
PY
)"
  if [ -n "${CUDA_PY_LIB_DIRS}" ]; then
    export LD_LIBRARY_PATH="${CUDA_PY_LIB_DIRS}${LD_LIBRARY_PATH:+:${LD_LIBRARY_PATH}}"
  fi
}

preflight_qwen3_moe_vram() {
  MODEL_NAME="${MODEL}" DTYPE_NAME="${DTYPE}" QUANTIZE_NAME="${QUANTIZE}" python - <<'PY'
import json
import os
from pathlib import Path

import torch

model = os.environ.get("MODEL_NAME", "")
dtype = os.environ.get("DTYPE_NAME", "bf16")
quantize = os.environ.get("QUANTIZE_NAME", "none")
allow_low_vram = os.environ.get("ALLOW_LOW_VRAM", "0") == "1"
min_vram_gb = float(os.environ.get("QWEN3_MOE_MIN_VRAM_GB", "64"))

def looks_like_qwen3_coder_30b_a3b(value: str) -> bool:
    text = value.replace("\\", "/").lower()
    if "qwen3-coder-30b-a3b" in text:
        return True
    cfg_path = Path(value) / "config.json"
    if not cfg_path.exists():
        return False
    try:
        cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
    except Exception:
        return False
    return (
        str(cfg.get("model_type", "")).lower() == "qwen3_moe"
        and int(cfg.get("num_hidden_layers", 0) or 0) >= 48
        and int(cfg.get("hidden_size", 0) or 0) >= 2048
        and int(cfg.get("num_experts", cfg.get("moe_intermediate_size", 0)) or 0) > 0
    )

