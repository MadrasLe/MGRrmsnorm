print(f"VRAM preflight: {gpu_name} has {vram_gb:.2f} GiB; required >= {min_vram_gb:.0f} GiB for BF16/FP16 Qwen3-Coder-30B-A3B")
if vram_gb < min_vram_gb:
    raise SystemExit(
        "ERROR: this fresh VM cannot load Qwen3-Coder-30B-A3B in BF16/FP16. "
        "The weights alone are about 58 GiB before KV/workspace. "
        "Use A100-80GB or RTX PRO 6000 Blackwell 96GB, or set ALLOW_LOW_VRAM=1 "
        "only for an explicitly quantized/offload experiment."
    )
