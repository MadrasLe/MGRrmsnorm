"""Run MGX Prophet and vLLM in one L4 session, then compare the new summaries.

This intentionally compares only files generated by this invocation. It avoids
mixing a Prophet result from one Colab session with a vLLM result from another.
"""

from __future__ import annotations

import argparse
import glob
import importlib.util
import os
import shlex
import site
import subprocess
import sys
import sysconfig
import time
from pathlib import Path
from typing import Any

from compare_inference_summaries import compare, write_csv


ROOT = Path(__file__).resolve().parents[1]
MATRIX = ROOT / "benchmarks" / "benchmark_inference_matrix.py"
PROPHET_SUITE = ROOT / "benchmarks" / "run_qwen25_mgx_prophet_matrix_t4.py"
DEFAULT_MGX = "artifacts/Qwen--Qwen2.5-3B-Instruct-fp16.mgx"


def shell_join(cmd: list[str]) -> str:
    if os.name == "nt":
        return subprocess.list2cmdline(cmd)
    return shlex.join(cmd)


def cuda_python_lib_dirs() -> list[str]:
    roots: list[str] = []
    try:
        roots.extend(site.getsitepackages())
    except Exception:
        pass
    try:
        roots.append(site.getusersitepackages())
    except Exception:
        pass
    try:
        paths = sysconfig.get_paths()
        roots.extend([paths.get("purelib") or "", paths.get("platlib") or ""])
    except Exception:
        pass

    seen: list[str] = []
    for root in roots:
        if not root:
            continue
        for pattern in ("nvidia/**/lib", "nvidia/**/lib64"):
            for raw in glob.glob(str(Path(root) / pattern), recursive=True):
                path = str(Path(raw))
                if Path(path).is_dir() and path not in seen:
                    seen.append(path)
    return seen


def vllm_env() -> dict[str, str]:
    env = os.environ.copy()
    cuda_dirs = cuda_python_lib_dirs()
    if cuda_dirs:
        old_ld = env.get("LD_LIBRARY_PATH", "")
        env["LD_LIBRARY_PATH"] = ":".join(cuda_dirs + ([old_ld] if old_ld else []))
    old_pythonpath = env.get("PYTHONPATH", "")
    env["PYTHONPATH"] = str(ROOT) + (os.pathsep + old_pythonpath if old_pythonpath else "")
    return env


def module_exists(name: str) -> bool:
    return importlib.util.find_spec(name) is not None


def ensure_vllm(args: argparse.Namespace) -> None:
    if module_exists("vllm") and not args.vllm_version:
        return
    if not args.install_vllm:
        raise SystemExit("vLLM is not installed. Re-run with --install-vllm or install it manually.")
    package = "vllm"
    if args.vllm_version:
        package = f"vllm=={args.vllm_version}"
    cmd = [sys.executable, "-m", "pip", "install", "-U", package]
    print()
    print("=" * 80)
    print("INSTALLING vLLM")
    print("=" * 80)
    print(shell_join(cmd))
    subprocess.run(cmd, cwd=str(ROOT), check=True)


def check_vllm_import(env: dict[str, str], expected_version: str = "") -> None:
    check = ""
    if expected_version:
        check = (
            f"; assert getattr(vllm, '__version__', '') == {expected_version!r}, "
            f"(getattr(vllm, '__version__', 'unknown'), {expected_version!r})"
        )
    cmd = [
        sys.executable,
        "-c",
        (
            "import torch, vllm; "
            "from vllm import LLM, SamplingParams; "
            "print('vLLM import OK', getattr(vllm, '__version__', 'unknown'), "
            "'torch', torch.__version__, 'cuda_available', torch.cuda.is_available())"
            + check
        ),
    ]
    print()
    print("=" * 80)
    print("CHECKING vLLM IMPORT")
    print("=" * 80)
    print(shell_join(cmd))
    subprocess.run(cmd, cwd=str(ROOT), env=env, check=True)


def prophet_cmd(args: argparse.Namespace, run_id: str) -> list[str]:
    cmd = [
        sys.executable,
        str(PROPHET_SUITE),
        "--hardware-label",
        args.hardware_label,
        "--modes",
        "prophet-warm",
        "--model",
        args.model,
        "--mgx",
        args.mgx,
        "--dtype",
        args.dtype,
        "--quantize",
        args.quantize,
        "--batch-sizes",
        args.batch_sizes,
        "--prompt-tokens",
        args.prompt_tokens,
        "--max-new-tokens",
        str(args.max_new_tokens),
        "--max-seq-len",
        str(args.max_seq_len),
        "--max-batch-size",
        str(args.max_batch_size),
        "--num-blocks",
        str(args.num_blocks),
        "--block-size",
        str(args.block_size),
        "--repeats",
        str(args.repeats),
        "--warmup",
        str(args.warmup),
        "--out-dir",
        args.out_dir,
        "--run-id",
        run_id,
        "--ignore-eos",
        "--prophet-batch-exact-restore",
        "--prophet-live-prefix-cache",
        "--prophet-resident-cache",
        "--prophet-resident-cache-max-entries",
        str(args.prophet_resident_cache_max_entries),
    ]
    if args.paged_decode_gqa_group > 0:
        cmd.extend(["--paged-decode-gqa-group", str(args.paged_decode_gqa_group)])
    if args.paged_decode_warps > 0:
        cmd.extend(["--paged-decode-warps", str(args.paged_decode_warps)])
    if args.paged_decode_block_unroll != 0:
        cmd.extend(["--paged-decode-block-unroll", str(args.paged_decode_block_unroll)])
    if args.paged_decode_splits > 0:
        cmd.extend(["--paged-decode-splits", str(args.paged_decode_splits)])
    if args.paged_decode_log:
        cmd.append("--paged-decode-log")
    if args.mgx_decode_cuda_graphs:
        cmd.append("--decode-cuda-graphs")
    if args.mgx_decode_cuda_graphs_prefer_step:
        cmd.append("--decode-cuda-graphs-prefer-step")
    if args.mgx_decode_cuda_graphs_shape_cache:
        cmd.append("--decode-cuda-graphs-shape-cache")
    else:
        cmd.append("--no-decode-cuda-graphs-shape-cache")
    if args.mgx_decode_cuda_graphs_shared_shape_cache:
        cmd.append("--decode-cuda-graphs-shared-shape-cache")
    else:
        cmd.append("--no-decode-cuda-graphs-shared-shape-cache")
    if args.mgx_decode_cuda_graphs_stable_max_blocks:
        cmd.append("--decode-cuda-graphs-stable-max-blocks")
    else:
        cmd.append("--no-decode-cuda-graphs-stable-max-blocks")
    cmd.extend(["--decode-cuda-graphs-min-batch", str(args.mgx_decode_cuda_graphs_min_batch)])
    cmd.extend(["--decode-cuda-graphs-log-limit", str(args.mgx_decode_cuda_graphs_log_limit)])
    if not args.export_if_missing:
        cmd.append("--no-export-if-missing")
    if args.force_export:
        cmd.append("--force-export")
    if args.local_files_only:
        cmd.append("--local-files-only")
    return cmd


def vllm_cmd(args: argparse.Namespace, run_id: str) -> list[str]:
    cmd = [
        sys.executable,
        str(MATRIX),
        "--backend",
        "vllm",
        "--model",
        args.model,
        "--tokenizer",
        args.model,
        "--hardware-label",
        args.hardware_label,
        "--batch-sizes",
        args.batch_sizes,
        "--prompt-tokens",
        args.prompt_tokens,
        "--max-new-tokens",
        str(args.max_new_tokens),
        "--repeats",
        str(args.repeats),
        "--warmup",
        str(args.warmup),
        "--out-dir",
        args.out_dir,
        "--run-id",
        f"{run_id}_vllm",
        "--device",
        "cuda",
        "--dtype",
        args.dtype,
        "--max-seq-len",
        str(args.max_seq_len),
        "--vllm-max-model-len",
        str(args.max_seq_len),
        "--vllm-gpu-memory-utilization",
        str(args.vllm_gpu_memory_utilization),
        "--ignore-eos",
    ]
    if args.vllm_enforce_eager:
        cmd.append("--vllm-enforce-eager")
    if args.vllm_language_model_only:
        cmd.append("--vllm-language-model-only")
    if args.vllm_disable_cudagraph_memory_profiler:
        cmd.append("--vllm-disable-cudagraph-memory-profiler")
    return cmd


def prophet_summary(args: argparse.Namespace, run_id: str) -> Path:
    stem = f"{run_id}_prophet-warm_{args.hardware_label}_megagemm-prophet"
    return Path(args.out_dir) / f"{stem}_summary.json"


def vllm_summary(args: argparse.Namespace, run_id: str) -> Path:
    stem = f"{run_id}_vllm_{args.hardware_label}_vllm"
    return Path(args.out_dir) / f"{stem}_summary.json"


def write_report(
    args: argparse.Namespace,
    run_id: str,
    prophet_path: Path,
    vllm_path: Path,
    rows: list[dict[str, Any]],
) -> Path:
    report = Path(args.out_dir) / f"{run_id}_prophet_vs_vllm_report.md"
    lines = [
        "# Qwen2.5 MGX Prophet vs vLLM L4",
        "",
        f"- Run id: `{run_id}`",
        f"- Hardware: `{args.hardware_label}`",
        f"- Model: `{args.model}`",
        f"- MGX: `{args.mgx}`",
        f"- Batch sizes: `{args.batch_sizes}`",
        f"- Prompt tokens: `{args.prompt_tokens}`",
        f"- Max new tokens: `{args.max_new_tokens}`",
        f"- Repeats: `{args.repeats}`",
        f"- KV block size: `{args.block_size}`",
        f"- Prophet paged decode GQA group: `{args.paged_decode_gqa_group}`",
        f"- Prophet paged decode warps: `{args.paged_decode_warps or 'auto'}`",
        f"- Prophet paged decode block unroll: `{args.paged_decode_block_unroll or 'auto'}`",
        f"- Prophet paged decode splits: `{args.paged_decode_splits or 'auto'}`",
        f"- Prophet decode CUDA Graphs: `{args.mgx_decode_cuda_graphs}`",
        f"- Prophet decode CUDA Graph shape cache: `{args.mgx_decode_cuda_graphs_shape_cache}`",
        f"- Prophet decode CUDA Graph shared shape cache: `{args.mgx_decode_cuda_graphs_shared_shape_cache}`",
        f"- Prophet decode CUDA Graph stable max blocks: `{args.mgx_decode_cuda_graphs_stable_max_blocks}`",
        f"- Prophet summary: `{prophet_path}`",
        f"- vLLM summary: `{vllm_path}`",
        "",
        "Both summaries above were produced by this same invocation.",
        "",
        "| Scenario | Batch | Prompt | Prophet tok/s | vLLM tok/s | Prophet vs vLLM | Winner |",
        "|---|---:|---:|---:|---:|---:|---|",
    ]
    for row in rows:
        winner = "Prophet" if row["winner"] == "left" else "vLLM"
        lines.append(
            "| {scenario} | {batch} | {prompt} | {left:.2f} | {right:.2f} | {pct:+.1f}% | {winner} |".format(
                scenario=row["scenario"],
                batch=row["batch_size"],
                prompt=row["prompt_tokens"],
                left=row["left_tok_s"],
                right=row["right_tok_s"],
                pct=row["left_vs_right_pct"],
                winner=winner,
            )
        )
    report.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description="One-session L4 comparison: MGX Prophet vs vLLM.")
    parser.add_argument("--model", default="Qwen/Qwen2.5-3B-Instruct")
    parser.add_argument("--mgx", default=DEFAULT_MGX)
    parser.add_argument("--hardware-label", default="1xl4")
    parser.add_argument("--out-dir", default="bench_results/l4_prophet_vs_vllm")
    parser.add_argument("--run-id", default="")
    parser.add_argument("--batch-sizes", default="1,2,4,8")
    parser.add_argument("--prompt-tokens", default="512,1024,2048")
    parser.add_argument("--max-new-tokens", type=int, default=128)
    parser.add_argument("--repeats", "--runs", dest="repeats", type=int, default=3)
    parser.add_argument("--warmup", type=int, default=1)
    parser.add_argument("--dtype", default="fp16", choices=["fp16", "bf16", "fp32"])
    parser.add_argument("--quantize", default="none", choices=["none", "int8", "fp8", "awq"])
    parser.add_argument("--max-seq-len", type=int, default=4096)
    parser.add_argument("--max-batch-size", type=int, default=8)
    parser.add_argument("--num-blocks", type=int, default=1024)
    parser.add_argument("--block-size", type=int, default=64)
    parser.add_argument("--prophet-resident-cache-max-entries", type=int, default=16)
    parser.add_argument(
        "--paged-decode-gqa-group",
        type=int,
        default=0,
        choices=[0, 2, 4],
        help="Prophet/MGX decode GQA grouping. 0 keeps generic, 2/4 enable grouped KV reuse paths.",
    )
    parser.add_argument("--paged-decode-warps", type=int, default=0, help="0 keeps auto.")
    parser.add_argument(
        "--paged-decode-block-unroll",
        type=int,
        default=0,
        choices=[-1, 0, 1, 2],
        help="0 keeps auto, -1/1 force no unroll, 2 forces unroll-by-2 where supported.",
    )
    parser.add_argument("--paged-decode-splits", type=int, default=0, help="0 keeps auto.")
    parser.add_argument("--paged-decode-log", action="store_true")
    parser.add_argument(
        "--mgx-decode-cuda-graphs",
        action=argparse.BooleanOptionalAction,
        default=False,
        help="Enable MGX scheduler CUDA Graph replay for decode.",
    )
    parser.add_argument(
        "--mgx-decode-cuda-graphs-prefer-step",
        action=argparse.BooleanOptionalAction,
        default=False,
        help="Prefer MGX graph-aware decode step path when CUDA Graph decode is enabled.",
    )
    parser.add_argument(
        "--mgx-decode-cuda-graphs-shape-cache",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="Reuse MGX decode CUDA Graphs by batch/table shape instead of concrete seq_ids.",
    )
    parser.add_argument(
        "--mgx-decode-cuda-graphs-shared-shape-cache",
        action=argparse.BooleanOptionalAction,
        default=False,
        help="Experimentally reuse MGX shape CUDA Graphs across Scheduler instances.",
    )
    parser.add_argument(
        "--mgx-decode-cuda-graphs-stable-max-blocks",
        action=argparse.BooleanOptionalAction,
        default=True,
        help=(
            "Capture MGX shape-cache decode graphs with loop_blocks fixed to "
            "table_blocks for the burst, relying on paged attention's seq_len mask."
        ),
    )
    parser.add_argument("--mgx-decode-cuda-graphs-min-batch", type=int, default=8)
    parser.add_argument("--mgx-decode-cuda-graphs-log-limit", type=int, default=6)
    parser.add_argument("--vllm-gpu-memory-utilization", type=float, default=0.90)
    parser.add_argument(
        "--vllm-version",
        default="",
        help=(
            "Pin vLLM to an exact pip version before running, for example "
            "`0.22.1` or `0.23.0`. Empty means use the currently installed "
            "version, or install/upgrade latest if vLLM is missing."
        ),
    )
    parser.add_argument("--vllm-enforce-eager", action="store_true")
    parser.add_argument("--vllm-language-model-only", action="store_true")
    parser.add_argument("--vllm-disable-cudagraph-memory-profiler", action="store_true")
    parser.add_argument("--install-vllm", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument("--export-if-missing", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument("--force-export", action="store_true")
    parser.add_argument("--local-files-only", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    run_id = args.run_id or time.strftime("qwen25_prophet_vs_vllm_l4_%Y%m%d_%H%M%S")
    Path(args.out_dir).mkdir(parents=True, exist_ok=True)

    print("Qwen2.5 MGX Prophet vs vLLM one-session L4 suite")
    print(f"  run_id: {run_id}")
    print(f"  out:    {args.out_dir}")
    print(f"  model:  {args.model}")
    print(f"  mgx:    {args.mgx}")

    p_cmd = prophet_cmd(args, run_id)
    v_env = vllm_env()
    if not args.dry_run:
        ensure_vllm(args)
        v_env = vllm_env()
    v_cmd = vllm_cmd(args, run_id)

    print()
    print("=" * 80)
    print("MGX PROPHET WARM")
    print("=" * 80)
    print(shell_join(p_cmd))
    if not args.dry_run:
        subprocess.run(p_cmd, cwd=str(ROOT), check=True)

    if not args.dry_run:
        check_vllm_import(v_env, args.vllm_version)

    print()
    print("=" * 80)
    print("vLLM PREFIX CACHE")
    print("=" * 80)
    print(shell_join(v_cmd))
    if not args.dry_run:
        subprocess.run(v_cmd, cwd=str(ROOT), env=v_env, check=True)

    p_summary = prophet_summary(args, run_id)
    v_summary = vllm_summary(args, run_id)
    if args.dry_run:
        print()
        print(f"Would compare Prophet: {p_summary}")
        print(f"Would compare vLLM:    {v_summary}")
        return 0

    missing = [str(path) for path in (p_summary, v_summary) if not path.exists()]
    if missing:
        raise SystemExit("Missing expected summary file(s): " + ", ".join(missing))

    rows = compare(p_summary, v_summary)
    csv_path = Path(args.out_dir) / f"{run_id}_prophet_vs_vllm.csv"
    write_csv(csv_path, rows)
    report = write_report(args, run_id, p_summary, v_summary, rows)

    print()
    print("=" * 80)
    print("SAME-SESSION COMPARISON")
    print("=" * 80)
    print(f"Prophet summary: {p_summary}")
    print(f"vLLM summary:    {v_summary}")
    print()
    print("scenario,batch,prompt,prophet_tok_s,vllm_tok_s,prophet_vs_vllm_pct,winner")
    for row in rows:
        winner = "prophet" if row["winner"] == "left" else "vllm"
        print(
            f"{row['scenario']},{row['batch_size']},{row['prompt_tokens']},"
            f"{row['left_tok_s']:.2f},{row['right_tok_s']:.2f},"
            f"{row['left_vs_right_pct']:+.1f}%,{winner}"
        )
    print()
    print(f"Wrote CSV:    {csv_path}")
    print(f"Wrote report: {report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
